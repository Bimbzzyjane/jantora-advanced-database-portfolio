-- Jantora Superstores: PostgreSQL schema. Run on an EMPTY database.
BEGIN;
CREATE TABLE categories (
    category_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE branches (
    branch_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_name VARCHAR(120) NOT NULL UNIQUE,
    state VARCHAR(80) NOT NULL,
    address TEXT NOT NULL
);
CREATE TABLE customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(30),
    address TEXT
);
CREATE TABLE products (
    product_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id INTEGER NOT NULL REFERENCES categories(category_id),
    product_name VARCHAR(150) NOT NULL,
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    UNIQUE (category_id, product_name)
);
CREATE TABLE inventory (
    inventory_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id INTEGER NOT NULL REFERENCES branches(branch_id),
    product_id INTEGER NOT NULL REFERENCES products(product_id),
    quantity INTEGER NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    UNIQUE (branch_id, product_id)
);
CREATE TABLE orders (
    order_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INTEGER REFERENCES customers(customer_id),
    branch_id INTEGER NOT NULL REFERENCES branches(branch_id),
    order_type VARCHAR(12) NOT NULL CHECK (order_type IN ('ONLINE', 'IN_STORE')),
    order_status VARCHAR(20) NOT NULL DEFAULT 'PLACED'
        CHECK (order_status IN ('PLACED','PROCESSING','COMPLETED','CANCELLED')),
    ordered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (order_type <> 'ONLINE' OR customer_id IS NOT NULL)
);
CREATE TABLE order_items (
    order_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL REFERENCES orders(order_id),
    product_id INTEGER NOT NULL REFERENCES products(product_id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL CHECK (unit_price >= 0),
    UNIQUE (order_id, product_id)
);
CREATE TABLE payments (
    payment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL UNIQUE REFERENCES orders(order_id),
    amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    payment_method VARCHAR(20) NOT NULL CHECK (payment_method IN ('CARD','TRANSFER','CASH')),
    payment_status VARCHAR(20) NOT NULL CHECK (payment_status IN ('PENDING','PAID','FAILED')),
    paid_at TIMESTAMPTZ
);
CREATE TABLE deliveries (
    delivery_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INTEGER NOT NULL UNIQUE REFERENCES orders(order_id),
    delivery_address TEXT NOT NULL,
    delivery_status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (delivery_status IN ('PENDING','PROCESSING','OUT_FOR_DELIVERY','DELIVERED','FAILED')),
    dispatched_at TIMESTAMPTZ,
    delivered_at TIMESTAMPTZ,
    CHECK (delivered_at IS NULL OR dispatched_at IS NOT NULL),
    CHECK (delivered_at IS NULL OR delivered_at >= dispatched_at)
);
COMMIT;
